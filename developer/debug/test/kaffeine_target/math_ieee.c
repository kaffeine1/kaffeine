static BOOL is_nan(ULONG hi, ULONG lo)
{
    return (hi & 0x7FF00000) == 0x7FF00000 && ((hi & 0x000FFFFF) || lo);
}

/* Both doubles have the same sign and differ by at most tolerance in the
   last place; 64-bit arithmetic on 32-bit halves, without libgcc. */
static BOOL close_double(ULONG hi, ULONG lo, ULONG ehi, ULONG elo, ULONG tolerance)
{
    ULONG dhi, dlo;

    if (hi == ehi && lo == elo)
        return TRUE;
    if (!tolerance || ((hi ^ ehi) & 0x80000000))
        return FALSE;
    if (hi > ehi || (hi == ehi && lo > elo))
    {
        dlo = lo - elo;
        dhi = hi - ehi - (lo < elo);
    }
    else
    {
        dlo = elo - lo;
        dhi = ehi - hi - (elo < lo);
    }
    return dhi == 0 && dlo <= tolerance;
}

static struct Library *base_of(UBYTE lib)
{
    return lib == BAS ? MathIeeeDoubBasBase :
           lib == TRANS ? MathIeeeDoubTransBase : MathIeeeSingBasBase;
}

/* The condition codes and registers after a call made with in_ccr */
static BOOL check_frame(const struct IEEECall *call, UBYTE flags, UWORD in_ccr)
{
    UBYTE got = (call->n ? CC_N : 0) | (call->z ? CC_Z : 0) | (call->v ? CC_V : 0);
    BOOL xc = (call->x != 0) == ((in_ccr & CC_X) != 0) &&
              (call->c != 0) == ((in_ccr & CC_C) != 0);
    BOOL regs = call->d2 == call->in_d2 && call->d3 == call->in_d3 &&
                call->d4 == 0x44444444 && call->d5 == 0x55555555 && call->d6 == 0x66666666 &&
                call->a2 == 0xA2A2A2A2 && call->a3 == 0xA3A3A3A3 && call->a4 == 0xA4A4A4A4;

    if (got != flags || !xc || !regs)
    {
        Printf("     CCR in 0x%02lx: N Z V %ld %ld %ld (expected %ld %ld %ld), X %ld C %ld, registers %s\n",
               (LONG)in_ccr, (LONG)!!call->n, (LONG)!!call->z, (LONG)!!call->v,
               (LONG)!!(flags & CC_N), (LONG)!!(flags & CC_Z), (LONG)!!(flags & CC_V),
               (LONG)call->x, (LONG)!!call->c, (LONG)(regs ? "kept" : "changed"));
        return FALSE;
    }
    return TRUE;
}

static BOOL check_result(const struct Case *t, const struct IEEECall *call)
{
    BOOL ok;

    switch (t->kind)
    {
        case R_D:
            ok = close_double(call->d0, call->d1, t->hi, t->lo, t->tolerance);
            break;
        case R_NAN:
            ok = is_nan(call->d0, call->d1);
            break;
        default:    /* LONG or single precision in D0 */
            ok = call->d0 == t->hi;
            break;
    }
    if (!ok)
        Printf("     got D0 0x%08lx D1 0x%08lx, expected 0x%08lx 0x%08lx\n",
               call->d0, call->d1, t->hi, t->lo);
    return ok;
}

static void run_case(const struct Case *t)
{
    static const UWORD ccrs[] = { 0x00, CC_X | CC_N | CC_Z | CC_V | CC_C };
    BOOL ok = TRUE;
    ULONG i;

    for (i = 0; i < 2; i++)
    {
        struct IEEECall call = { 0 };

        call.in_d0 = t->d0;
        call.in_d1 = t->d1;
        call.in_d2 = t->d2;
        call.in_d3 = t->d3;
        call.in_ccr = ccrs[i];
        ieee_call(base_of(t->lib), -t->lvo, &call);
        ok = check_result(t, &call) && ok;
        ok = check_frame(&call, t->flags, ccrs[i]) && ok;
    }
    check(ok, t->what);
}

/* sin(0.5) and cos(0.5), from math_ieee_cases.py sincos */
#define SIN_HALF_HI 0x3FDEAEE8UL
#define SIN_HALF_LO 0x744B05F0UL
#define COS_HALF_HI 0x3FEC1528UL
#define COS_HALF_LO 0x065B7D50UL

/* IEEEDPSincos() returns the sine in D0/D1 and writes the cosine through A0
   as 8 big-endian bytes; the bytes around them must not change. Like the
   table cases, it runs with the incoming CCR all clear and all set. */
static void run_sincos(const char *what, ULONG hi, ULONG lo, ULONG sin_hi, ULONG sin_lo,
                       ULONG cos_hi, ULONG cos_lo, UBYTE flags, UBYTE tolerance)
{
    static const UWORD ccrs[] = { 0x00, CC_X | CC_N | CC_Z | CC_V | CC_C };
    static UBYTE area[24];
    BOOL ok = TRUE;
    ULONG i, j;

    for (j = 0; j < 2; j++)
    {
        struct IEEECall call = { 0 };
        ULONG got_hi, got_lo;
        BOOL guards = TRUE;

        for (i = 0; i < sizeof(area); i++)
            area[i] = 0xA5;
        call.in_d0 = hi;
        call.in_d1 = lo;
        call.in_a0 = (ULONG)(area + 8);
        call.in_ccr = ccrs[j];
        ieee_call(MathIeeeDoubTransBase, -54, &call);
        got_hi = ((ULONG)area[8] << 24) | ((ULONG)area[9] << 16) | ((ULONG)area[10] << 8) | area[11];
        got_lo = ((ULONG)area[12] << 24) | ((ULONG)area[13] << 16) | ((ULONG)area[14] << 8) | area[15];
        for (i = 0; i < 8; i++)
            guards = guards && area[i] == 0xA5 && area[16 + i] == 0xA5;

        if (!close_double(call.d0, call.d1, sin_hi, sin_lo, tolerance))
        {
            Printf("     sine 0x%08lx 0x%08lx, expected 0x%08lx 0x%08lx\n",
                   call.d0, call.d1, sin_hi, sin_lo);
            ok = FALSE;
        }
        if (!close_double(got_hi, got_lo, cos_hi, cos_lo, tolerance))
        {
            Printf("     cosine at A0 0x%08lx 0x%08lx, expected 0x%08lx 0x%08lx\n",
                   got_hi, got_lo, cos_hi, cos_lo);
            ok = FALSE;
        }
        if (!guards)
        {
            Printf("     a byte next to the cosine changed\n");
            ok = FALSE;
        }
        ok = check_frame(&call, flags, ccrs[j]) && ok;
    }
    check(ok, what);
}

int main(void)
{
    struct IEEECall call = { 0 };
    ULONG i;

    MathIeeeDoubBasBase = OpenLibrary((CONST_STRPTR)"mathieeedoubbas.library", 34);
    MathIeeeDoubTransBase = OpenLibrary((CONST_STRPTR)"mathieeedoubtrans.library", 34);
    MathIeeeSingBasBase = OpenLibrary((CONST_STRPTR)"mathieeesingbas.library", 34);
    if (!check(MathIeeeDoubBasBase != NULL, "OpenLibrary() of mathieeedoubbas.library") ||
        !check(MathIeeeDoubTransBase != NULL, "OpenLibrary() of mathieeedoubtrans.library") ||
        !check(MathIeeeSingBasBase != NULL, "OpenLibrary() of mathieeesingbas.library"))
        return test_done("math_ieee");
    /* The bridge looks for unknown libraries in LIBS68K:, which does not
       exist here: through Run, a requester would stop the program. */
    check(OpenLibrary((CONST_STRPTR)"kaffeine-missing.library", 0) == NULL,
          "OpenLibrary() of a missing library fails without a requester");

    for (i = 0; i < sizeof(cases) / sizeof(cases[0]); i++)
        run_case(&cases[i]);

    /* sin(0) = 0 and cos(0) = 1 are exact; 0.5 is compared within 2 units */
    run_sincos("IEEEDPSincos(0): sine 0 in D0/D1, cosine 1.0 big-endian at A0",
               0, 0, 0, 0, 0x3FF00000, 0, CC_Z, 0);
    run_sincos("IEEEDPSincos(0.5): sine in D0/D1, cosine big-endian at A0",
               0x3FE00000, 0, SIN_HALF_HI, SIN_HALF_LO, COS_HALF_HI, COS_HALF_LO, 0, 2);

    /* A NULL A0 must not be written; the sine still comes back */
    call.in_d0 = 0x3FE00000;
    call.in_ccr = 0;
    ieee_call(MathIeeeDoubTransBase, -54, &call);
    check(close_double(call.d0, call.d1, SIN_HALF_HI, SIN_HALF_LO, 2),
          "IEEEDPSincos() with A0 NULL returns the sine and writes nothing");

    CloseLibrary(MathIeeeSingBasBase);
    CloseLibrary(MathIeeeDoubTransBase);
    CloseLibrary(MathIeeeDoubBasBase);
    return test_done("math_ieee");
}
