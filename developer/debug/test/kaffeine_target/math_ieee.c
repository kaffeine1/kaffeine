/*
    Copyright (C) 2026, The AROS Development Team. All rights reserved.

    Every vector of mathieeedoubbas.library, mathieeedoubtrans.library and
    mathieeesingbas.library, called from 68k code. The program is built for the 68000 without FPU
    code, so it does not depend on the FPU startup. An assembly helper puts
    the arguments in D0/D1 and D2/D3 (and A0), sets the CCR, calls the
    vector and reads the condition codes with Scc and ADDX before any other
    instruction can change them. Each case runs with the incoming CCR all
    clear and with X, N, Z, V and C all set: N, Z and V must follow the
    result, X and C must not change, and D2 to D6 and A2 to A4 must survive.

    The table comes from math_ieee_cases.py: exact IEEE 754 results as bit
    patterns, and host libm results with a tolerance in units in the last
    place for the transcendental functions. The C code below never computes
    with floating point; it only compares bit patterns.
*/

#include <exec/types.h>
#include <exec/libraries.h>
#include <proto/exec.h>
#include <proto/dos.h>

#include "m68ktest.h"

#define CC_X 0x10
#define CC_N 0x08
#define CC_Z 0x04
#define CC_V 0x02
#define CC_C 0x01

/* Offsets are used by the assembly helper below. */
struct IEEECall
{
    ULONG in_d0, in_d1, in_d2, in_d3, in_a0;   /* 0 4 8 12 16 */
    UWORD in_ccr, pad;                          /* 20 22 */
    ULONG d0, d1;                               /* 24 28 */
    UBYTE z, n, v, c;                           /* 32 33 34 35, from Scc */
    UBYTE x, pad2[3];                           /* 36, from ADDX */
    ULONG d2, d3, d4, d5, d6;                   /* 40 44 48 52 56 */
    ULONG a2, a3, a4;                           /* 60 64 68 */
};

void ieee_call(struct Library *base, LONG lvo, struct IEEECall *call);

__asm__(
"	.text\n"
"	.align	2\n"
"	.globl	_ieee_call\n"
"_ieee_call:\n"
"	movem.l d2-d7/a2-a6,-(sp)\n"
"	move.l (48,sp),a6\n"
"	move.l (52,sp),d7\n"
"	move.l (56,sp),a5\n"
"	move.l (0,a5),d0\n"
"	move.l (4,a5),d1\n"
"	move.l (8,a5),d2\n"
"	move.l (12,a5),d3\n"
"	move.l (16,a5),a0\n"
"	move.l #0x44444444,d4\n"
"	move.l #0x55555555,d5\n"
"	move.l #0x66666666,d6\n"
"	move.l #0xA2A2A2A2,a2\n"
"	move.l #0xA3A3A3A3,a3\n"
"	move.l #0xA4A4A4A4,a4\n"
"	move.w (20,a5),ccr\n"
"	jsr (0,a6,d7.l)\n"
"	seq (32,a5)\n"
"	smi (33,a5)\n"
"	svs (34,a5)\n"
"	scs (35,a5)\n"
"	move.l d6,(56,a5)\n"
"	moveq #0,d6\n"
"	addx.l d6,d6\n"
"	move.b d6,(36,a5)\n"
"	move.l d0,(24,a5)\n"
"	move.l d1,(28,a5)\n"
"	move.l d2,(40,a5)\n"
"	move.l d3,(44,a5)\n"
"	move.l d4,(48,a5)\n"
"	move.l d5,(52,a5)\n"
"	move.l a2,(60,a5)\n"
"	move.l a3,(64,a5)\n"
"	move.l a4,(68,a5)\n"
"	movem.l (sp)+,d2-d7/a2-a6\n"
"	rts\n");

